-- Приводимо фактичну вагу гантельних підходів тренувань, початих до деплою правила (версія 7920bc19, 2026-11-23T08:36:28.697Z),
-- до ваги ОДНІЄЇ гантелі. prescribed_weight_kg не чіпаємо: його рахував бот з каталогу (мінімум/крок — уже «на гантель»).
-- Повтори, пропущені підходи, інші обладнання й пізніші тренування — без змін. Міграція одноразова (D1 веде журнал).
UPDATE `workout_sets` SET `weight_kg` = `weight_kg` / 2.0
WHERE `skipped` = 0
  AND `weight_kg` IS NOT NULL
  AND `exercise_id` IN (SELECT `id` FROM `exercises` WHERE `equipment` = 'dumbbell')
  AND `workout_id` IN (SELECT `id` FROM `workouts` WHERE `started_at` < 1795422988697);
