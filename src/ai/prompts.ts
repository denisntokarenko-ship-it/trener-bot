const WEEKDAYS = ["понеділок", "вівторок", "середа", "четвер", "пʼятниця", "субота", "неділя"] as const;

/** Перший рядок повідомлення користувача: сьогоднішня локальна дата й день тижня (`isoWeekday` 1–7). */
export function chatDateLine(today: string, isoWeekday: number): string {
  return `Сьогодні: ${today}, ${WEEKDAYS[isoWeekday - 1] ?? ""}.`;
}

/** Поточне повідомлення користувача для моделі: динамічний рядок + текст (текст — дані). */
export function chatUserMessage(text: string, today: string, isoWeekday: number): string {
  return `${chatDateLine(today, isoWeekday)}\n\n${text}`;
}
